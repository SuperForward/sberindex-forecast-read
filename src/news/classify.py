"""Тип шока по тексту новости: словари основ слов, без обучения.

Словари, а не языковая модель: каждое решение объяснимо (видно, какое слово
сработало), результат воспроизводим, не нужен интернет и ключи API. Типы те
же, что у кандидатов в шоки из данных Росстата, плюс ЧС (стихийные бедствия
и техногенные аварии) – самый частый повод резкого сдвига расходов.

Новость может получить несколько типов («закрытие завода и увольнения»).
Новости без совпадений – «прочее», в признаки не идут.
"""

import re

TYPES = {
    "emergency": "ЧС: бедствие или авария",
    "production": "производственный (локальный рынок)",
    "fiscal": "финансово-бюджетный",
    "social": "социально-демографический",
    "prices": "цены и тарифы",
}

LEXICON = {
    "emergency": [r"паводк", r"наводнен", r"подтопл", r"затоп", r"прорыв\w* дамб", r"режим\w* (?:ЧС|чрезвычайн)",
                  r"чрезвычайн\w* ситуац", r"эвакуац", r"эвакуир", r"лесн\w* пожар", r"природн\w* пожар",
                  r"землетрясен", r"ураган", r"смерч", r"снегопад", r"ледян\w* дожд", r"авари\w* на",
                  r"без (?:света|электричества|тепла|воды)", r"обрушен", r"взрыв на", r"обстрел", r"беспилотник",
                  r"\bБПЛА\b", r"ракетн\w* опасност", r"атак\w* (?:ВСУ|дрон)"],
    "production": [r"закры\w*(?:\s+\w+){0,2}\s+(?:завод|фабрик|комбинат|предприят|производств|шахт|цех)",
                   r"останов\w*(?:\s+\w+){0,2}\s+(?:завод|производств|работ|добыч|конвейер)", r"банкрот",
                   r"сокращ\w* (?:сотрудник|работник|персонал|штат)", r"увол\w*", r"простой", r"забастов",
                   r"откры\w*(?:\s+\w+){0,2}\s+(?:завод|фабрик|производств|цех)",
                   r"запуст\w*(?:\s+\w+){0,2}\s+(?:завод|производств)",
                   r"градообразующ", r"инвестпроект", r"четырехдневк|четырёхдневк|сокращенн\w* недел"],
    "fiscal": [r"задолженност\w* по (?:зарплат|заработн)", r"задерж\w* (?:зарплат|заработн|выплат)",
               r"дефицит\w* бюджет", r"бюджет\w* (?:дефицит|долг|сокращ|секвест)", r"госдолг\w* регион",
               r"дотаци", r"трансферт", r"секвест", r"долг\w* (?:регион|муниципал|област)"],
    "social": [r"мигра", r"переселен", r"отток\w* населен", r"демограф", r"рождаемост", r"смертност",
               r"мобилизац", r"выплат\w* (?:семьям|пострадавш|компенсац)", r"компенсац\w* пострадавш",
               r"пенси\w* (?:повыш|индексац)"],
    "prices": [r"подорож", r"цен\w* на (?:бензин|топлив|продукт|жиль|электроэнерг)", r"тариф",
               r"стоимост\w* (?:проезда|жкх|жилищно)", r"инфляц", r"дефицит\w* (?:бензин|топлив)"],
}
_RX = {t: re.compile("|".join(v), re.I) for t, v in LEXICON.items()}


def classify(text: str) -> list[str]:
    """Типы шока, найденные в тексте (может быть пусто)."""
    return [t for t, rx in _RX.items() if rx.search(str(text))]


def explain(text: str) -> dict[str, str]:
    """Какое слово сработало для каждого типа – для проверки глазами."""
    out = {}
    for t, rx in _RX.items():
        m = rx.search(str(text))
        if m:
            out[t] = m.group(0)
    return out
